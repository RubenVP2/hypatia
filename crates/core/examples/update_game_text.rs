//! Regenerates the Game Text tables (`crates/shared/data/game_text/<lang>.tsv`): the names of
//! champions, items, runes, rune trees, summoner spells and skins by Riot ID, in each language
//! Hypatia speaks, from CommunityDragon's copy of the client's game data.
//!
//! Run from the workspace root after a patch: `cargo run -p hypatia-core --example update_game_text`.
//! A development tool only: the app never makes this request, it reads the tables it ships with.

use std::fmt::Write as _;
use std::path::Path;

use serde_json::Value;

const BASE: &str = "https://raw.communitydragon.org/latest";
/// Hypatia language code → CommunityDragon locale folder.
const LANGUAGES: [(&str, &str); 2] = [("en", "default"), ("fr", "fr_fr")];
const OUT_DIR: &str = "crates/shared/data/game_text";

#[tokio::main(flavor = "current_thread")]
async fn main() -> Result<(), Box<dyn std::error::Error>> {
    let http = reqwest::Client::builder()
        .user_agent("hypatia-game-text")
        .build()?;
    let meta: Value = get(&http, &format!("{BASE}/content-metadata.json")).await?;
    let patch = meta
        .get("version")
        .and_then(Value::as_str)
        .unwrap_or("unknown")
        .split('+')
        .next()
        .unwrap_or("unknown")
        .to_string();

    for (lang, locale) in LANGUAGES {
        let root = format!("{BASE}/plugins/rcp-be-lol-game-data/global/{locale}/v1");
        let mut rows: Vec<(&str, i64, String)> = Vec::new();
        let champions = get(&http, &format!("{root}/champion-summary.json")).await?;
        // Game-mode variants (`Jade_Garen`, id 60086) reuse their champion's name with a
        // higher id; only the real champion, the lowest id, is named.
        let mut champions: Vec<_> = named(&champions, "champion").collect();
        champions.sort_by_key(|row| row.1);
        let mut seen = std::collections::HashSet::new();
        champions.retain(|row| seen.insert(row.2.clone()));
        rows.extend(champions);
        let items = get(&http, &format!("{root}/items.json")).await?;
        rows.extend(named(&items, "item"));
        let perks = get(&http, &format!("{root}/perks.json")).await?;
        rows.extend(named(&perks, "perk"));
        let styles = get(&http, &format!("{root}/perkstyles.json")).await?;
        rows.extend(named(
            styles.get("styles").unwrap_or(&Value::Null),
            "perkstyle",
        ));
        let spells = get(&http, &format!("{root}/summoner-spells.json")).await?;
        rows.extend(named(&spells, "spell"));
        let skins = get(&http, &format!("{root}/skins.json")).await?;
        for skin in skins.as_object().into_iter().flat_map(|m| m.values()) {
            rows.extend(row("skin", skin));
            let tiers = skin
                .get("questSkinInfo")
                .and_then(|q| q.get("tiers"))
                .and_then(Value::as_array);
            for tier in tiers.into_iter().flatten() {
                rows.extend(row("skin", tier));
            }
        }

        rows.sort_by(|a, b| (a.0, a.1).cmp(&(b.0, b.1)));
        rows.dedup_by(|a, b| a.0 == b.0 && a.1 == b.1);
        let mut out = format!(
            "# Game Text ({lang}), patch {patch}, from CommunityDragon `{locale}`.\n\
             # Generated by `cargo run -p hypatia-core --example update_game_text`; do not edit.\n\
             # kind\tid\tname\n"
        );
        for (kind, id, name) in &rows {
            writeln!(out, "{kind}\t{id}\t{name}")?;
        }
        let path = Path::new(OUT_DIR).join(format!("{lang}.tsv"));
        std::fs::create_dir_all(OUT_DIR)?;
        std::fs::write(&path, out)?;
        println!("{} rows -> {}", rows.len(), path.display());
    }
    Ok(())
}

async fn get(http: &reqwest::Client, url: &str) -> Result<Value, Box<dyn std::error::Error>> {
    Ok(http
        .get(url)
        .send()
        .await?
        .error_for_status()?
        .json()
        .await?)
}

fn named<'a>(
    list: &'a Value,
    kind: &'static str,
) -> impl Iterator<Item = (&'static str, i64, String)> + 'a {
    list.as_array()
        .into_iter()
        .flatten()
        .filter_map(move |entry| row(kind, entry))
}

/// One `(kind, id, name)` row; nameless and placeholder entries (id ≤ 0) are skipped.
fn row(kind: &'static str, entry: &Value) -> Option<(&'static str, i64, String)> {
    let id = entry
        .get("id")
        .and_then(Value::as_i64)
        .filter(|id| *id > 0)?;
    let name = entry.get("name").and_then(Value::as_str)?;
    let name = name.split_whitespace().collect::<Vec<_>>().join(" ");
    (!name.is_empty()).then_some((kind, id, name))
}
